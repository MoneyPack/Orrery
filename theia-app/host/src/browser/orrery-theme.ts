/**
 * Orrery workbench themes.
 *
 * The palette is the Mission Control design system from `src/styles.css`: graphite neutrals,
 * one oxidized amber, hairlines instead of cards. Both themes are generated from the same
 * structure so a colour decision is made once and lands in every surface — workbench chrome,
 * Monaco editor, terminal, diff, Git decorations, and syntax tokens.
 *
 * The output is a VS Code colour theme (https://code.visualstudio.com/api/references/theme-color),
 * which Theia's Monaco theming service consumes directly.
 */

