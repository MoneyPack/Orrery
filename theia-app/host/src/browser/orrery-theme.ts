/** Appends an alpha byte to a 6-digit hex colour. */
export function alpha(hex: string, fraction: number): string {
  const byte = Math.round(Math.max(0, Math.min(1, fraction)) * 255).toString(16).padStart(2, "0");
  return `${hex}${byte}`;
}

